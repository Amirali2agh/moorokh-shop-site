import os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

url = os.environ.get('SHOP_URL', 'http://127.0.0.1:8876/')
review = Path('.impeccable/review')
review.mkdir(parents=True, exist_ok=True)
with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    for name, width, height in [('desktop', 1440, 960), ('mobile', 390, 844)]:
        page = browser.new_page(viewport={'width': width, 'height': height}, reduced_motion='reduce')
        errors, failures, writes = [], [], []
        page.on('pageerror', lambda error: errors.append(str(error)))
        page.on('requestfailed', lambda r: failures.append(r.url))
        page.on('response', lambda r: failures.append(f'{r.status} {r.url}') if r.status >= 400 else None)
        page.on('request', lambda r: writes.append(r.url) if r.method != 'GET' or not r.url.startswith(url) else None)
        assert page.goto(url).ok
        expect(page.locator('#products article')).to_have_count(7)
        expect(page.locator('.announcement')).to_contain_text('نسخه دمو')
        page.evaluate('document.fonts.ready')
        page.evaluate("Promise.all([...document.images].map(i=>{i.loading='eager';return i.decode()}))")
        assert page.evaluate('document.documentElement.scrollWidth === innerWidth')
        page.screenshot(path=str(review / f'{name}.png'), full_page=True)
        page.locator('#dots button').nth(1).click()
        expect(page.locator('h1')).to_have_text('کتانی اسپرت')
        page.locator('#hero-link').click()
        expect(page.locator('#products article')).to_have_count(1)
        page.get_by_role('searchbox').fill('چیزی که وجود ندارد')
        expect(page.locator('#products')).to_contain_text('محصولی پیدا نشد')
        page.get_by_role('searchbox').fill('تی شرت نخی')
        expect(page.locator('#products article')).to_have_count(1)
        page.locator('#products .favorite').click()
        page.locator('.actions [data-act=favorites]').click()
        expect(page.locator('#panel-body')).to_contain_text('تی‌شرت نخی مینیمال')
        page.keyboard.press('Escape')
        page.locator('#products .product-main').click()
        page.locator('#add-form button').click()
        expect(page.locator('#add-form')).to_be_visible()
        page.locator('#add-form select').select_option('M')
        page.locator('#add-form button').click()
        expect(page.locator('#count')).to_have_text('۱')
        page.reload()
        expect(page.locator('#count')).to_have_text('۱')
        page.get_by_role('button', name='سبد خرید', exact=True).click()
        page.locator('#panel [data-act=inc]').click()
        expect(page.locator('#count')).to_have_text('۲')
        page.locator('#panel [data-act=dec]').click()
        expect(page.locator('#count')).to_have_text('۱')
        page.locator('#panel [data-act=checkout]').click()
        expect(page.locator('#panel')).to_contain_text('بدون درگاه پرداخت')
        page.locator('#panel [data-act=place]').click()
        expect(page.locator('#panel-title')).to_have_text('سفارش آزمایشی ثبت شد')
        expect(page.locator('#count')).to_have_text('۰')
        assert not (errors or failures or writes), (errors, failures, writes)
        print(name, 'passed: assets, RTL width, carousel, filtering, favorites, size, persisted cart, quantities, simulated checkout, no network writes')
        page.close()
    browser.close()

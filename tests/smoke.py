import os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

url = os.environ.get('SHOP_URL', 'http://127.0.0.1:8876/')
review = Path('.impeccable/review')
review.mkdir(parents=True, exist_ok=True)
with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    for name, width, height in [('desktop', 1440, 960), ('mobile', 390, 844), ('narrow-mobile', 320, 720)]:
        page = browser.new_page(viewport={'width': width, 'height': height}, reduced_motion='reduce')
        errors, failures, writes = [], [], []
        page.on('pageerror', lambda error: errors.append(str(error)))
        page.on('requestfailed', lambda r: failures.append(r.url))
        page.on('response', lambda r: failures.append(f'{r.status} {r.url}') if r.status >= 400 else None)
        page.on('request', lambda r: writes.append(r.url) if r.method != 'GET' or not r.url.startswith(url) else None)
        assert page.goto(url).ok
        expect(page.locator('#products article')).to_have_count(14)
        expect(page.locator('#products')).to_contain_text('کراتین نانو گلد مو')
        expect(page.locator('#products')).to_contain_text('استعلام قیمت')
        expect(page.locator('#products article').first.locator('[data-act=add]')).to_contain_text('افزودن به سبد خرید')
        assert not any(term in page.locator('body').inner_text() for term in ('دمو', 'نمایشی', 'آزمایشی', 'بروشور', 'راستی‌آزمایی'))
        page.evaluate('document.fonts.ready')
        page.evaluate("Promise.all([...document.images].map(i=>{i.loading='eager';return i.decode()}))")
        assert page.evaluate('document.documentElement.scrollWidth === innerWidth')
        page.screenshot(path=str(review / f'{name}.png'), full_page=True)
        page.locator('#dots button').nth(1).click()
        expect(page.locator('h1')).to_have_text('مراقبت روزانه مو')
        page.locator('#hero-link').click()
        expect(page.locator('#products article')).to_have_count(3)
        page.get_by_role('searchbox').fill('هیچ محصولی')
        expect(page.locator('#products')).to_contain_text('محصولی پیدا نشد')
        page.get_by_role('searchbox').fill('روغن آرگان')
        expect(page.locator('#products article')).to_have_count(1)
        page.locator('#products .favorite').click()
        page.locator('.actions [data-act=favorites]').click()
        expect(page.locator('#panel-body')).to_contain_text('روغن آرگان')
        expect(page.locator('#panel-body')).not_to_contain_text('استعلام')
        page.keyboard.press('Escape')
        page.locator('.nav [data-act=help]').click()
        expect(page.locator('#panel-body')).not_to_contain_text('دمو')
        expect(page.locator('#panel-body')).not_to_contain_text('بروشور')
        expect(page.locator('#panel-body')).not_to_contain_text('راستی‌آزمایی')
        page.keyboard.press('Escape')
        page.get_by_role('searchbox').fill('')
        page.locator('#products article').first.locator('[data-act=add]').click()
        expect(page.locator('#count')).to_have_text('۱')
        expect(page.locator('#products article').first.locator('.card-qty output')).to_have_text('۱')
        page.locator('#products article').first.locator('.card-qty [data-act=inc]').click()
        expect(page.locator('#count')).to_have_text('۲')
        page.locator('#products article').first.locator('.card-qty [data-act=dec]').click()
        expect(page.locator('#count')).to_have_text('۱')
        page.reload()
        expect(page.locator('#count')).to_have_text('۱')
        page.locator('#products .product-main').first.click()
        expect(page.locator('#panel')).not_to_contain_text('قیمت: استعلام از فروشنده')
        expect(page.locator('#panel')).not_to_contain_text('راستی‌آزمایی نشده‌اند')
        expect(page.locator('#panel')).not_to_contain_text('پرداخت و ثبت سفارش واقعی انجام نمی‌شود')
        expect(page.locator('#panel .detail-cart-action [data-act=inc]')).to_be_visible()
        page.locator('#panel .detail-cart-action [data-act=inc]').click()
        expect(page.locator('#count')).to_have_text('۲')
        page.keyboard.press('Escape')
        page.locator('#products article').nth(1).locator('.product-main').click()
        expect(page.locator('#panel [data-act=add]')).to_contain_text('افزودن به سبد خرید')
        page.locator('#panel [data-act=add]').click()
        expect(page.locator('#count')).to_have_text('۳')
        page.reload()
        expect(page.locator('#count')).to_have_text('۳')
        page.locator('#cart-button').click()
        expect(page.locator('#panel-title')).to_have_text('سبد خرید')
        expect(page.locator('#panel-body')).to_contain_text('تعداد کالاها')
        expect(page.locator('#panel-body')).not_to_contain_text('استعلام')
        expect(page.locator('#panel .cart-item')).to_have_count(2)
        expect(page.locator('#panel .cart-heading b')).to_have_text('۲ محصول')
        expect(page.locator('#panel .cart-heading span')).to_have_text('۳ کالا در سبد')
        expect(page.locator('#panel .cart-summary .summary-row').nth(0)).to_contain_text('۲ محصول')
        expect(page.locator('#panel .cart-summary .summary-row').nth(1)).to_contain_text('۳ عدد')
        expect(page.locator('#panel .cart-summary .continue-shopping')).to_be_visible()
        assert page.evaluate('document.documentElement.scrollWidth === innerWidth')
        cart_bounds = page.locator('#panel').bounding_box()
        assert cart_bounds and cart_bounds['x'] >= 0 and cart_bounds['x'] + cart_bounds['width'] <= width
        page.locator('#panel .cart-item').first.locator('[data-act=inc]').click()
        expect(page.locator('#count')).to_have_text('۴')
        page.locator('#panel .cart-item').first.locator('[data-act=dec]').click()
        expect(page.locator('#count')).to_have_text('۳')
        page.locator('#panel .cart-item').last.locator('[data-act=remove]').click()
        expect(page.locator('#count')).to_have_text('۲')
        expect(page.locator('#panel .cart-item')).to_have_count(1)
        expect(page.locator('#panel-body button[data-act=checkout]')).to_have_count(0)
        page.locator('#panel [data-act=confirm-clear]').click()
        expect(page.locator('#panel')).to_contain_text('همه کالاهای سبد خرید حذف شوند؟')
        page.locator('#panel [data-act=cart]').click()
        expect(page.locator('#count')).to_have_text('۲')
        page.locator('#panel [data-act=confirm-clear]').click()
        page.locator('#panel [data-act=clear]').click()
        expect(page.locator('#panel-title')).to_have_text('سبد خرید')
        expect(page.locator('#count')).to_have_text('۰')
        expect(page.locator('#panel')).to_contain_text('سبد خرید خالی است')
        page.locator('#panel-body [data-act=continue]').click()
        expect(page.locator('#panel')).not_to_be_visible()
        assert not (errors or failures or writes), (errors, failures, writes)
        print(name, 'passed: 14-product catalog, images, RTL width, categories, search, favorites, add from card/detail, quantity controls, persistence, summary counts, removal, clear confirmation and empty-state return')
        page.close()
    browser.close()
